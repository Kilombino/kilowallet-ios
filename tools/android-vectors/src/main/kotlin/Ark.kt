import com.kilombino.pyblockwatch.ark.ArkDerive
import com.kilombino.pyblockwatch.crypto.Bip39
import java.io.File

/**
 * Runs the Android app's Ark word derivation (ark/ArkDerive.kt, verbatim) over a few wallets, with
 * and without a passphrase, and writes what it answered as vectors for the iOS port.
 */
fun main(args: Array<String>) {
    val out = File(args[0])
    val commit = args[1]
    val abandon = (List(11) { "abandon" } + "about")
    val zoo = (List(23) { "zoo" } + "vote")
    val fromEntropy = Bip39.fromEntropy(ByteArray(32) { (it * 7 + 3).toByte() })
    val cases = listOf(
        abandon to "", abandon to "TREZOR", zoo to "", fromEntropy to "", fromEntropy to "pässphrase ünicode",
    )
    val rows = cases.map { (w, p) -> listOf(w.joinToString(" "), p, ArkDerive.words(w, p).joinToString(" ")).joinToString("\t") }
    out.writeText(
        """
        |package com.kilombino.kilowallet.core
        |
        |// GENERATED by tools/android-vectors (./gradlew -p tools/android-vectors ark) from the Android app's
        |// ark/ArkDerive.kt (Kilombino/kilowallet commit $commit), verbatim.
        |// words, passphrase, Ark words
        |internal object ArkVectors {
        |    const val COMMIT = "$commit"
        |    val TSV = ""${'"'}
        |${rows.joinToString("\n")}
        |""${'"'}
        |}
        |""".trimMargin()
    )
    println("wrote ${out.absolutePath} (${rows.size} rows)")
}
