import com.kilombino.pyblockwatch.data.AndroidMaturity
import java.io.File

/**
 * Runs the Android app's coinbase maturity rule (Scanner companion, verbatim) over heights at and
 * around every boundary, and writes what it answered as vectors for the iOS port.
 */
fun main(args: Array<String>) {
    val out = File(args[0])
    val commit = args[1]
    val heights = listOf(1, 100, 973_438, 973_439, 973_440, 973_441, 979_917, 979_918, 979_919, 979_920, 979_921, 985_000, 1_200_000)
    val tips = listOf(0, 973_539, 979_919, 979_920, 986_398, 986_399, 1_005_838, 1_005_839, 1_005_840, 1_300_000)
    val rows = heights.flatMap { h ->
        tips.map { t ->
            listOf(h, t, AndroidMaturity.maturityFor(h), AndroidMaturity.maturesAt(h),
                if (AndroidMaturity.mayBeImmature(h, t)) 1 else 0,
                if (AndroidMaturity.immature(true, h, t)) 1 else 0,
                if (AndroidMaturity.immature(false, h, t)) 1 else 0).joinToString("\t")
        }
    }
    out.writeText(
        """
        |package com.kilombino.kilowallet.core
        |
        |// GENERATED by tools/android-vectors (./gradlew -p tools/android-vectors maturity) from the
        |// Android app's coinbase maturity rule (Kilombino/kilowallet commit $commit), verbatim.
        |// height, tip, maturityFor, maturesAt, mayBeImmature, immature(coinbase), immature(not coinbase)
        |internal object MaturityVectors {
        |    const val COMMIT = "$commit"
        |    const val HISTORICAL_MATURITY = ${AndroidMaturity.HISTORICAL_MATURITY}
        |    const val LONG_MATURITY = ${AndroidMaturity.LONG_MATURITY}
        |    const val LONG_START = ${AndroidMaturity.LONG_START}
        |    val TSV = ""${'"'}
        |${rows.joinToString("\n")}
        |""${'"'}
        |}
        |""".trimMargin()
    )
    println("wrote ${out.absolutePath} (${rows.size} rows)")
}
